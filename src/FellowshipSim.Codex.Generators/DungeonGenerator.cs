using System.Collections.Immutable;
using System.Globalization;
using System.Text;
using System.Text.Json;
using Fellowship.SDK.Documents;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace FellowshipSim.Codex.Generators;

/// <summary>
/// Writes <c>GameDungeons</c> in <c>FellowshipSim.Core.Domain</c>: each dungeon of the game data with creature
/// placements, as a <c>CodexDungeon</c> of its ID (a FellowshipLogs fight's <c>gameZone</c> ID), name and placements. A
/// placement is a <c>CodexPlacement</c>: the creature's game ID, its world position's x and y, and its patrol (the index of
/// the dungeon's patrol path it walks; null for none). The game data is the AdditionalFiles <c>entities.jsonl</c>, read through
/// FellowshipAnalyzer.Codex.SDK; <see cref="CreatureGenerator"/> reports missing game data.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class DungeonGenerator : IIncrementalGenerator
{
    private const string EntitiesName = "entities.jsonl";
    private const string Namespace = "FellowshipSim.Core.Domain";

    private sealed record Placement(int CreatureId, double X, double Y, int? Patrol);

    private sealed record Dungeon(int Id, string Name, EquatableArray<Placement> Placements);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var dungeons = context.AdditionalTextsProvider
            .Where(f => Path.GetFileName(f.Path) == EntitiesName)
            .Select((file, ct) => Read(file, ct))
            .Collect();
        context.RegisterSourceOutput(dungeons, (spc, all) => Write(spc, all.SelectMany(d => d).OrderBy(d => d.Id).ToList()));
    }

    private static EquatableArray<Dungeon> Read(AdditionalText file, CancellationToken ct)
    {
        var dungeons = new List<Dungeon>();
        var text = file.GetText(ct);
        if (text == null) return new([]);
        foreach (var line in text.Lines)
        {
            ct.ThrowIfCancellationRequested();
            string json = line.ToString();
            // Only dungeon lines are read in full; CreatureGenerator reports a line that does not read.
            if (!json.Contains("\"$type\":\"dungeon\"")) continue;
            try
            {
                if (JsonSerializer.Deserialize<EntityDocument>(json, EntityDocuments.Options) is not DungeonDocument d) continue;
                var placements = (d.Placements ?? [])
                    .Where(p => p.Creature != null && p.Position != null)
                    .Select(p => new Placement(p.Creature!.Id, p.Position!.X, p.Position.Y, p.Patrol))
                    .ToList();
                if (placements.Count > 0) dungeons.Add(new Dungeon(d.Id, (d.Name ?? "").Trim(), new([.. placements])));
            }
            catch (JsonException)
            {
            }
        }
        return new([.. dungeons]);
    }

    private static void Write(SourceProductionContext context, List<Dungeon> dungeons)
    {
        var source = new StringBuilder()
            .Append("// <auto-generated> by FellowshipSim.Codex.Generators from the game data. </auto-generated>\n")
            .Append("#nullable enable\n")
            .Append("namespace ").Append(Namespace).Append(";\n\n")
            .Append("/// <summary>\n")
            .Append("/// A creature placed in a dungeon of the game data: its game ID, its world position's x and y, and the index of\n")
            .Append("/// the patrol path it walks (null for none).\n")
            .Append("/// </summary>\n")
            .Append("public sealed record CodexPlacement(int CreatureId, double X, double Y, int? Patrol);\n\n")
            .Append("/// <summary>A dungeon of the game data: its ID (a FellowshipLogs fight's gameZone ID), name and creature placements.</summary>\n")
            .Append("public sealed record CodexDungeon(int Id, string Name, IReadOnlyList<CodexPlacement> Placements);\n\n")
            .Append("/// <summary>Every dungeon of the game data with creature placements.</summary>\n")
            .Append("public static class GameDungeons\n{\n")
            .Append("    /// <summary>Every dungeon, by ID.</summary>\n")
            .Append("    public static IReadOnlyList<CodexDungeon> All { get; } =\n    [\n");
        foreach (var dungeon in dungeons)
        {
            source.Append("        new(").Append(dungeon.Id).Append(", ").Append(Literal(dungeon.Name)).Append(",\n        [\n");
            foreach (var p in dungeon.Placements)
            {
                source.Append("            new(").Append(p.CreatureId).Append(", ").Append(Number(p.X)).Append(", ").Append(Number(p.Y))
                    .Append(", ").Append(p.Patrol?.ToString(CultureInfo.InvariantCulture) ?? "null").Append("),\n");
            }
            source.Append("        ]),\n");
        }
        source.Append("    ];\n\n")
            .Append("    private static readonly Dictionary<int, CodexDungeon> _byId = All.ToDictionary(d => d.Id);\n\n")
            .Append("    /// <summary>The dungeon with ID <paramref name=\"id\"/> (a FellowshipLogs fight's gameZone ID); null when there is none.</summary>\n")
            .Append("    public static CodexDungeon? ById(int id) => _byId.GetValueOrDefault(id);\n")
            .Append("}\n");
        context.AddSource("GameDungeons.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

    private static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    private static string Number(double value) => value.ToString("R", CultureInfo.InvariantCulture);
}
