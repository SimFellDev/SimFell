using System.Text;

namespace FellowshipSim.Codex.Generators;

/// <summary>
/// The source of a <c>partial</c> static class in <c>FellowshipSim.Core.Import</c> with game data tables. Several
/// generators write parts of one class (<c>GameIcons</c>, <c>GameHeroData</c>); the part with the class's summary is the
/// one the class's own generator writes.
/// </summary>
internal static class GameTables
{
    public const string Namespace = "FellowshipSim.Core.Import";

    /// <summary>
    /// The class part with <paramref name="tables"/>, each with its entries in order. An entry with a key an earlier entry
    /// of its table has is left out.
    /// </summary>
    public static string Write(string className, string? summary, IEnumerable<GameTable> tables, string? buildDate)
    {
        var source = new StringBuilder()
            .Append("// <auto-generated> by FellowshipSim.Codex.Generators from the game data")
            .Append(buildDate != null ? $" of {buildDate}" : "").Append(". </auto-generated>\n")
            .Append("#nullable enable\n")
            .Append("namespace ").Append(Namespace).Append(";\n\n");
        if (summary != null)
        {
            source.Append("/// <summary>\n");
            foreach (string line in summary.Split('\n')) source.Append("/// ").Append(line).Append('\n');
            source.Append("/// </summary>\n");
        }
        source.Append("public static partial class ").Append(className).Append("\n{\n");
        bool first = true;
        foreach (var table in tables)
        {
            if (!first) source.Append('\n');
            first = false;
            string dictionary = $"global::System.Collections.Generic.Dictionary<{table.KeyType}, {table.ValueType}>";
            source.Append("    /// <summary>").Append(table.Summary).Append("</summary>\n")
                .Append("    public static global::System.Collections.Generic.IReadOnlyDictionary<").Append(table.KeyType).Append(", ").Append(table.ValueType)
                .Append("> ").Append(table.Name).Append(" { get; } = new ").Append(dictionary)
                .Append(table.IgnoreCase ? "(global::System.StringComparer.OrdinalIgnoreCase)" : "()").Append("\n    {\n");
            var keys = new HashSet<string>(table.IgnoreCase ? StringComparer.OrdinalIgnoreCase : StringComparer.Ordinal);
            foreach (var entry in table.Entries)
            {
                if (!keys.Add(entry.Key)) continue;
                source.Append("        [").Append(entry.Key).Append("] =").Append(entry.Value.StartsWith("\n", StringComparison.Ordinal) ? "" : " ")
                    .Append(entry.Value).Append(",\n");
            }
            source.Append("    };\n");
        }
        source.Append("}\n");
        return source.ToString();
    }

    public static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
