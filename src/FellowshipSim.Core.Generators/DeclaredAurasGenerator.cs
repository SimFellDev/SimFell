using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace FellowshipSim.Core.Generators;

/// <summary>
/// Writes the table <c>AuraDef.DeclaredOn</c> reads: for each class, its <c>public static</c> fields of type
/// <c>AuraDef</c> and then those of its base classes, in declaration order.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class DeclaredAurasGenerator : IIncrementalGenerator
{
    private const string AuraDefName = "FellowshipSim.Core.Domain.AuraDef";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var classes = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax { TypeParameterList: null },
                static (ctx, ct) => ClassOf(ctx, ct))
            .Where(static c => c != null)
            .Collect();
        context.RegisterSourceOutput(classes, static (spc, list) => Emit(spc, list!));
    }

    /// <summary>"type|field,field" for a class whose hierarchy declares public static AuraDef fields, or null.</summary>
    private static string? ClassOf(GeneratorSyntaxContext ctx, System.Threading.CancellationToken ct)
    {
        if (ctx.SemanticModel.GetDeclaredSymbol(ctx.Node, ct) is not INamedTypeSymbol type) return null;
        for (var outer = type; outer != null; outer = outer.ContainingType)
        {
            if (outer.DeclaredAccessibility is Accessibility.Private or Accessibility.Protected) return null;
        }
        var fields = new List<string>();
        for (var t = type; t != null; t = t.BaseType)
        {
            string owner = t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            foreach (var field in t.GetMembers().OfType<IFieldSymbol>())
            {
                if (field.IsStatic && field.DeclaredAccessibility == Accessibility.Public && field.Type.ToDisplayString() == AuraDefName)
                {
                    fields.Add($"{owner}.{field.Name}");
                }
            }
        }
        return fields.Count == 0 ? null : type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "|" + string.Join(",", fields);
    }

    private static void Emit(SourceProductionContext spc, ImmutableArray<string> classes)
    {
        var s = new StringBuilder();
        s.AppendLine("// <auto-generated/> by FellowshipSim.Core.Generators.DeclaredAurasGenerator");
        s.AppendLine("#nullable enable");
        s.AppendLine("namespace FellowshipSim.Core.Domain;");
        s.AppendLine();
        s.AppendLine("partial record AuraDef");
        s.AppendLine("{");
        s.AppendLine("    private static global::System.Collections.Generic.Dictionary<global::System.Type, AuraDef[]>? _declared;");
        s.AppendLine();
        s.AppendLine("    private static global::System.Collections.Generic.Dictionary<global::System.Type, AuraDef[]> Declared => _declared ??= new()");
        s.AppendLine("    {");
        foreach (string entry in classes.Distinct())
        {
            int bar = entry.IndexOf('|');
            s.AppendLine($"        [typeof({entry.Substring(0, bar)})] = [{entry.Substring(bar + 1).Replace(",", ", ")}],");
        }
        s.AppendLine("    };");
        s.AppendLine("}");
        spc.AddSource("AuraDef.Declared.g.cs", SourceText.From(s.ToString(), Encoding.UTF8));
    }
}
