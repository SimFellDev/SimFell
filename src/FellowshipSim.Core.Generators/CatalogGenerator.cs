using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace FellowshipSim.Core.Generators;

/// <summary>
/// Writes the constructors <c>Catalog</c> uses: each hero class by its class name, and each talent, augmentation, glyph,
/// legendary, weapon, relic passive and dungeon affix class with a public constructor without parameters as a constructor in
/// <c>TalentConstructors</c>, <c>AugmentationConstructors</c> (from its rank), <c>GlyphConstructors</c> (from its rank),
/// <c>LegendaryConstructors</c>, <c>WeaponConstructors</c>, <c>RelicPassiveConstructors</c> and <c>DungeonAffixConstructors</c>. FellowshipSim.Codex.Generators
/// writes a talent's <c>TalentId</c>, an augmentation's <c>&lt;Type&gt;Id</c>, a glyph's <c>GlyphId</c> and
/// <c>GlyphName</c>, a legendary's <c>HeroName</c> and <c>ItemIds</c>, the weapon ability IDs, and a relic passive's
/// <c>RelicPassiveId</c> and <c>RelicPassiveItems</c>. A generator never reads another's output, so <c>Catalog</c> reads
/// them from an instance.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class CatalogGenerator : IIncrementalGenerator
{
    private enum Kind { Hero, Talent, Augmentation, Glyph, Weapon, RelicPassive, Legendary, DungeonAffix }

    private static readonly (string Base, Kind Kind)[] Bases =
    [
        ("FellowshipSim.Core.Domain.Hero", Kind.Hero),
        ("FellowshipSim.Core.Domain.Talent", Kind.Talent),
        ("FellowshipSim.Core.Customization.Augmentations.Augmentation", Kind.Augmentation),
        ("FellowshipSim.Core.Customization.Glyphs.Glyph", Kind.Glyph),
        ("FellowshipSim.Core.Customization.Weapons.Weapon", Kind.Weapon),
        ("FellowshipSim.Core.Customization.RelicPassives.RelicPassive", Kind.RelicPassive),
        ("FellowshipSim.Core.Customization.Legendaries.Legendary", Kind.Legendary),
        ("FellowshipSim.Core.Dungeons.Affixes.DungeonAffix", Kind.DungeonAffix),
    ];

    /// <summary>One catalog class: its kind, full name and short name.</summary>
    /// <remarks>A class with value equality, so the generator's cache compares entries by value.</remarks>
    private sealed class Entry(Kind kind, string typeName, string shortName) : System.IEquatable<Entry>
    {
        public Kind Kind { get; } = kind;
        public string TypeName { get; } = typeName;
        public string ShortName { get; } = shortName;

        public bool Equals(Entry? other) => other != null && Kind == other.Kind && TypeName == other.TypeName && ShortName == other.ShortName;

        public override bool Equals(object? obj) => Equals(obj as Entry);

        public override int GetHashCode() => TypeName.GetHashCode();
    }

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var entries = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax { BaseList: not null } c
                                    && !c.Modifiers.Any(SyntaxKind.AbstractKeyword) && c.TypeParameterList == null,
                static (ctx, ct) => EntryOf(ctx, ct))
            .Where(static e => e != null)
            .Collect();
        context.RegisterSourceOutput(entries, static (spc, list) => Emit(spc, list!));
    }

    private static Entry? EntryOf(GeneratorSyntaxContext ctx, System.Threading.CancellationToken ct)
    {
        if (ctx.SemanticModel.GetDeclaredSymbol(ctx.Node, ct) is not INamedTypeSymbol type || type.IsAbstract) return null;
        if (!type.InstanceConstructors.Any(c => c.Parameters.Length == 0 && c.DeclaredAccessibility == Accessibility.Public)) return null;
        Kind? kind = null;
        for (var b = type.BaseType; b != null && kind == null; b = b.BaseType)
        {
            string name = b.ToDisplayString();
            foreach (var (baseName, k) in Bases)
            {
                if (name == baseName) kind = k;
            }
        }
        if (kind == null) return null;
        return new Entry(kind.Value, type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), type.Name);
    }

    private static void Emit(SourceProductionContext spc, ImmutableArray<Entry> found)
    {
        var entries = new List<Entry>();
        var seen = new HashSet<string>();
        foreach (var entry in found)
        {
            if (seen.Add(entry.TypeName)) entries.Add(entry);
        }

        var s = new StringBuilder();
        s.AppendLine("// <auto-generated/> by FellowshipSim.Core.Generators.CatalogGenerator");
        s.AppendLine("#nullable enable");
        s.AppendLine("namespace FellowshipSim.Core;");
        s.AppendLine();
        s.AppendLine("partial class Catalog");
        s.AppendLine("{");

        var heroes = entries.Where(e => e.Kind == Kind.Hero).ToList();
        s.AppendLine("    private static (string Name, global::System.Type Type)[] HeroClasses =>");
        s.AppendLine("    [");
        foreach (var h in heroes) s.AppendLine($"        ({Literal(h.ShortName)}, typeof({h.TypeName})),");
        s.AppendLine("    ];");
        s.AppendLine();
        s.AppendLine("    private static global::FellowshipSim.Core.Domain.Hero? NewHero(string name)");
        s.AppendLine("    {");
        foreach (var h in heroes)
        {
            s.AppendLine($"        if (string.Equals(name, {Literal(h.ShortName)}, global::System.StringComparison.OrdinalIgnoreCase)) return new {h.TypeName}();");
        }
        s.AppendLine("        return null;");
        s.AppendLine("    }");
        s.AppendLine();

        Constructors(s, "TalentConstructors", "global::FellowshipSim.Core.Domain.Talent", entries.Where(e => e.Kind == Kind.Talent));
        Constructors(s, "AugmentationConstructors", "global::FellowshipSim.Core.Customization.Augmentations.Augmentation",
            entries.Where(e => e.Kind == Kind.Augmentation), "int", "rank", " { Rank = rank }");
        Constructors(s, "GlyphConstructors", "global::FellowshipSim.Core.Customization.Glyphs.Glyph",
            entries.Where(e => e.Kind == Kind.Glyph), "int", "rank", " { Rank = rank }");
        Constructors(s, "LegendaryConstructors", "global::FellowshipSim.Core.Customization.Legendaries.Legendary", entries.Where(e => e.Kind == Kind.Legendary));
        Constructors(s, "WeaponConstructors", "global::FellowshipSim.Core.Customization.Weapons.Weapon", entries.Where(e => e.Kind == Kind.Weapon));
        Constructors(s, "RelicPassiveConstructors", "global::FellowshipSim.Core.Customization.RelicPassives.RelicPassive",
            entries.Where(e => e.Kind == Kind.RelicPassive));
        Constructors(s, "DungeonAffixConstructors", "global::FellowshipSim.Core.Dungeons.Affixes.DungeonAffix", entries.Where(e => e.Kind == Kind.DungeonAffix));
        s.AppendLine("}");

        spc.AddSource("Catalog.g.cs", SourceText.From(s.ToString(), Encoding.UTF8));
    }

    /// <summary>
    /// A list of each class's constructor: without parameters, or with one parameter of <paramref name="parameterType"/>
    /// named <paramref name="parameter"/> for <paramref name="initializer"/> to read.
    /// </summary>
    private static void Constructors(StringBuilder s, string property, string baseType, IEnumerable<Entry> classes,
        string? parameterType = null, string? parameter = null, string initializer = "")
    {
        string func = parameterType == null ? baseType : $"{parameterType}, {baseType}";
        string arguments = parameter ?? "()";
        s.AppendLine($"    private static global::System.Func<{func}>[] {property} =>");
        s.AppendLine("    [");
        foreach (var entry in classes) s.AppendLine($"        {arguments} => new {entry.TypeName}(){initializer},");
        s.AppendLine("    ];");
        s.AppendLine();
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);
}
