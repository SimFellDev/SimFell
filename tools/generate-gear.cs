// Writes src/FellowshipSim.Core/Import/GameGearData.cs: every hero's gear as the Codex has it, for the build editor's gear
// slots. Each item that drops in a dungeon, of a slot a build wears, with its stats untempered at item level 315 (a
// legendary at its own item level), its most tempers, the dungeons it drops in and its icon; a weapon with the ability
// its weapon power grants.
//
// The stats come from the Codex API (codex.fellowshipanalyzer.com/api/item?hero=...&itemLevel=...&upgrades=...), which
// works them out from the datamine's stat calculation; the hero names and each weapon power's ability come from the
// datamine export. A temper adds 1 to each of an item's stats (the Codex's StatRows.Magnitude: the magnitude plus the
// tempers, then rounded): the script checks every item at its most tempers against that. Run it again after a new
// datamine:
//
//     dotnet run tools/generate-gear.cs [path/to/entities.jsonl]
//
// The default path is the Codex cache, ~/.fellowsim/cache/codex/entities.jsonl.
using System.Text.Json.Nodes;

const int ItemLevel = 315;
const string Api = "https://codex.fellowshipanalyzer.com/api/item";

string root = Path.GetDirectoryName((string)AppContext.GetData("EntryPointFileDirectoryPath")!)!;
string output = Path.Combine(root, "src", "FellowshipSim.Core", "Import", "GameGearData.cs");
string path = args.Length > 0
    ? args[0]
    : Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".fellowsim", "cache", "codex", "entities.jsonl");

var rows = File.ReadLines(path).Where(line => line.Trim().Length > 0).Select(line => JsonNode.Parse(line)!.AsObject()).ToList();
var heroes = rows.Where(r => Text(r, "$type") == "hero").Select(r => Text(r, "name")!).Order(StringComparer.Ordinal).ToList();
// A weapon item grants a weapon power, and the power its ability.
var powerAbility = rows.Where(r => Text(r, "$type") == "weapon-power")
    .ToDictionary(r => Int(r, "id"), r => Int(r["grants"]!.AsArray().First(g => g!["type"]!.GetValue<string>() == "ability")!.AsObject(), "id"));

// The Codex's slot names, as the build's gear kinds.
var kinds = new Dictionary<string, string>
{
    ["Head"] = "Head", ["Shoulders"] = "Shoulders", ["Back"] = "Back", ["Chest"] = "Chest", ["Hands"] = "Hands", ["Legs"] = "Legs",
    ["Feet"] = "Feet", ["Neck"] = "Neck", ["Wrists"] = "Wrist", ["Ring"] = "Ring", ["Relic"] = "Relic", ["Weapon"] = "Weapon",
};
string[] statNames = ["Stamina", "Primary", "Critical Strike", "Expertise", "Haste", "Spirit"];
string[] primaries = ["Strength", "Agility", "Intellect"];

using var http = new HttpClient { Timeout = TimeSpan.FromMinutes(2) };
http.DefaultRequestHeaders.UserAgent.ParseAdd("FellowshipSim/1.0");

var lines = new List<string>
{
    "// <auto-generated> by tools/generate-gear.cs from the Codex. Run the script again after a new datamine instead of",
    "// editing this file. </auto-generated>",
    "namespace FellowshipSim.Core.Import;",
    "",
    "/// <summary>",
    $"/// Every hero's gear as the Codex has it: each item that drops in a dungeon, with its stats untempered at item level {ItemLevel}",
    "/// (a legendary at its own item level), by hero name. <see cref=\"GearItem.StatsAt\"/> adds the tempers.",
    "/// </summary>",
    "public static class GameGearData",
    "{",
    "    /// <summary>Each hero's gear, by hero name, in slot order and then by name.</summary>",
    "    public static IReadOnlyDictionary<string, GearItem[]> Items { get; } = new Dictionary<string, GearItem[]>(StringComparer.OrdinalIgnoreCase)",
    "    {",
};
int total = 0;
foreach (string hero in heroes)
{
    var untempered = await ListAsync(hero, ItemLevel, 0);
    var tempered = new Dictionary<(int Level, int Tempers), Dictionary<int, JsonObject>>();
    var items = new List<(int Order, string Name, string Line)>();
    foreach (var (id, row) in untempered)
    {
        if (Text(row, "slot") is not { } slot || !kinds.TryGetValue(slot, out string? kind)) continue;
        var dungeons = (row["sources"]?.AsArray() ?? []).Where(s => Text(s!.AsObject(), "kind") == "Dungeon")
            .Select(s => Text(s!.AsObject(), "name")!).ToList();
        if (dungeons.Count == 0) continue;
        bool legendary = (row["rarities"]?.AsArray() ?? []).Any(r => r!.GetValue<string>() == "Legendary");
        int level = legendary ? Int(row, "itemLevel") : ItemLevel;
        var at = level == ItemLevel ? row : (await ListAsync(hero, level, 0, cache: tempered))[id];
        int[] stats = Stats(at);
        int maxTempers = Int(at["magnitudes"]!.AsObject(), "maxUpgrades");
        if (maxTempers > 0)
        {
            // The item at its most tempers is its untempered stats with the tempers added to each.
            int[] most = Stats((await ListAsync(hero, level, maxTempers, cache: tempered))[id]);
            int[] expected = stats.Select(s => s == 0 ? 0 : s + maxTempers).ToArray();
            if (!most.SequenceEqual(expected))
            {
                throw new InvalidOperationException($"{hero}'s {Text(row, "name")} at {maxTempers} tempers is [{string.Join(", ", most)}], not [{string.Join(", ", expected)}].");
            }
        }
        int weaponAbility = kind == "Weapon" && row["grants"] is JsonObject g && Text(g, "type") == "weapon-power" ? powerAbility[Int(g, "id")] : 0;
        string icon = Text(row, "icon")!.Split('/')[^1].Replace("_full.webp", "");
        string name = Text(row, "name")!;
        items.Add((kinds.Keys.ToList().IndexOf(slot), name,
            $"            new({id}, {Cs(name)}, GearKind.{kind}, {level}, {maxTempers}, {(legendary ? "true" : "false")}, {weaponAbility}, " +
            $"new({string.Join(", ", stats)}), [{string.Join(", ", dungeons.Select(Cs))}], {Cs(icon)}),"));
    }
    lines.Add($"        [{Cs(hero)}] =");
    lines.Add("        [");
    lines.AddRange(items.OrderBy(i => i.Order).ThenBy(i => i.Name, StringComparer.Ordinal).Select(i => i.Line));
    lines.Add("        ],");
    total += items.Count;
    Console.WriteLine($"{hero}: {items.Count} items");
}
lines.AddRange(["    };", "}", ""]);
File.WriteAllText(output, string.Join("\n", lines));
Console.WriteLine($"Wrote {output} ({total} items)");

// Every item record of the hero at an item level and temper count, by ID, page by page.
async Task<Dictionary<int, JsonObject>> ListAsync(string hero, int level, int tempers, Dictionary<(int, int), Dictionary<int, JsonObject>>? cache = null)
{
    if (cache != null && cache.TryGetValue((level, tempers), out var known)) return known;
    var byId = new Dictionary<int, JsonObject>();
    for (int page = 1, pages = 1; page <= pages; page++)
    {
        string url = $"{Api}?hero={Uri.EscapeDataString(hero)}&itemLevel={level}&upgrades={tempers}&page={page}";
        var json = JsonNode.Parse(await http.GetStringAsync(url))!.AsObject();
        pages = Int(json, "pages");
        foreach (var r in json["rows"]!.AsArray()) byId[Int(r!.AsObject(), "id")] = r.AsObject();
    }
    if (cache != null) cache[(level, tempers)] = byId;
    return byId;
}

// Stamina, the hero's primary stat, Critical Strike, Expertise, Haste and Spirit; armor is not a stat a build holds.
int[] Stats(JsonObject row)
{
    var values = new int[statNames.Length];
    foreach (var s in row["magnitudes"]!["stats"]!.AsArray())
    {
        string stat = Text(s!.AsObject(), "stat")!;
        int at = Array.IndexOf(statNames, primaries.Contains(stat) ? "Primary" : stat);
        if (at >= 0) values[at] += Int(s.AsObject(), "value");
        else if (stat != "Armor") throw new InvalidOperationException($"{Text(row, "name")} has a stat no build holds: {stat}.");
    }
    return values;
}

static string? Text(JsonObject row, string key) => row[key] is JsonValue v && v.TryGetValue(out string? s) ? s : null;

static int Int(JsonObject row, string key) =>
    row[key] is JsonValue v && v.TryGetValue(out string? s) ? int.Parse(s) : (int)row[key]!.GetValue<double>();

static string Cs(string text) => "\"" + text.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
